import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { ledgerVerdicts } from "./ledger-verdicts.mjs";

const helper = new URL("../skills/yap/scripts/yap-cli.mjs", import.meta.url);
export const consumerVerdictsPath = new URL(
  "../skills/yap/scripts/refusal-verdicts.mjs",
  import.meta.url,
);
// Installed skills run outside the repository. Ship only their local codes' compiled verdicts.
export function consumerVerdictsSource() {
  const verdicts = Object.fromEntries(
    ledgerVerdicts(helper, /failure\("([A-Z_]+)"/g).map(({ code, entry }) => {
      return [
        code,
        {
          retryable: entry.retryable,
          ...(entry.retryAfterMs === undefined ? {} : { retryAfterMs: entry.retryAfterMs }),
        },
      ];
    }),
  );
  const entries = Object.entries(verdicts).map(
    ([code, verdict]) =>
      `  ${code}: {\n${Object.entries(verdict)
        .map(([key, value]) => `    ${key}: ${JSON.stringify(value)},\n`)
        .join("")}  },`,
  );
  return `// Generated by scripts/consumer-verdicts.mjs from the protocol refusal ledger.\nexport const refusalVerdicts = {\n${entries.join("\n")}\n};\n`;
}
if (import.meta.url === pathToFileURL(process.argv[1]).href)
  writeFileSync(consumerVerdictsPath, consumerVerdictsSource());
